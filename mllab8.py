def summation_unit(X, W): return np.dot(X, W)
def step(x): return np.where(x >= 0, 1, 0)

def get_perceptron_sse_history(X, y, W_init, lr, activation_func, max_epochs=1000, error_thresh=0.002):
    W = np.array(W_init, dtype=float)
    sse_hist = []
    for _ in range(max_epochs):
        epoch_sse = 0
        for i in range(len(X)):
            y_pred = activation_func(summation_unit(X[i], W))
            err = y[i] - y_pred
            epoch_sse += err ** 2
            W += lr * err * X[i]
        sse_hist.append(epoch_sse)
        if epoch_sse <= error_thresh:
            break
    return sse_hist

sse_history_a2 = get_perceptron_sse_history(X_logic, y_and, initial_W, alpha, step)

