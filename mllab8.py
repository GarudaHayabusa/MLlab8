# ==========================================
# A1: Core Functions
# ==========================================

def summation_unit(X, W):
    return np.dot(X, W)

def step(x):
    return np.where(x >= 0, 1, 0)

def bipolar_step(x):
    return np.where(x >= 0, 1, -1)

def sigmoid(x):
    x = np.clip(x, -500, 500) # Prevents overflow
    return 1 / (1 + np.exp(-x))

def sigmoid_derivative(x):
    sig = sigmoid(x)
    return sig * (1 - sig)

def relu(x):
    return np.maximum(0, x)

def calculate_error(y_true, y_pred):
    return y_true - y_pred

# ==========================================
# A2 - A5: Perceptron Training Function
# ==========================================

def train_perceptron(X, y, initial_weights, learning_rate, activation_func, max_epochs=1000, error_threshold=0.002):
    W = np.array(initial_weights, dtype=float)
    sse_history = []
    epochs_taken = max_epochs

    for epoch in range(max_epochs):
        epoch_sse = 0
        for i in range(len(X)):
            sum_val = summation_unit(X[i], W)
            y_pred = activation_func(sum_val)
            error = calculate_error(y[i], y_pred)
            epoch_sse += error ** 2
            W += learning_rate * error * X[i]

        sse_history.append(epoch_sse)
        if epoch_sse <= error_threshold:
            epochs_taken = epoch + 1
            break

    return W, sse_history, epochs_taken

# ==========================================
# A7: Matrix Pseudo-Inverse Function
# ==========================================

def pseudo_inverse_weights(X, y):
    return np.dot(np.linalg.pinv(X), y)

# ==========================================
# A8 - A9: Simple Neural Network (Backprop)
# ==========================================

def train_mlp_backprop(X, y, hidden_nodes=2, learning_rate=0.05, max_epochs=1000, error_threshold=0.002):
    np.random.seed(42)
    input_nodes = X.shape[1]
    output_nodes = y.shape[1] if len(y.shape) > 1 else 1

    W1 = np.random.randn(input_nodes, hidden_nodes)
    W2 = np.random.randn(hidden_nodes, output_nodes)

    sse_history = []
    epochs_taken = max_epochs
    y = y.reshape(-1, output_nodes)

    for epoch in range(max_epochs):
        hidden_input = np.dot(X, W1)
        hidden_output = sigmoid(hidden_input)
        final_input = np.dot(hidden_output, W2)
        final_output = sigmoid(final_input)

        error = y - final_output
        epoch_sse = np.sum(error ** 2)
        sse_history.append(epoch_sse)

        if epoch_sse <= error_threshold:
            epochs_taken = epoch + 1
            break

        d_output = error * sigmoid_derivative(final_input)
        error_hidden = d_output.dot(W2.T)
        d_hidden = error_hidden * sigmoid_derivative(hidden_input)

        W2 += hidden_output.T.dot(d_output) * learning_rate
        W1 += X.T.dot(d_hidden) * learning_rate

    return W1, W2, sse_history, epochs_taken

